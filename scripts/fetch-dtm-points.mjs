// DTM points after every race, built from the official standings of api.dtm.com: the source gives
// each entrant's points for every race and the season total, not the total after each race. The
// line is the running sum of the published race points and is kept only when it ends exactly at the
// published total; a championship where any entrant does not match is left out.
//
//   node scripts/fetch-dtm-points.mjs          every season the API has
//   node scripts/fetch-dtm-points.mjs 2026     one season, the others are kept
import { readFile, writeFile } from 'node:fs/promises';

const OUT = new URL('../src/series/dtm/data/standingProgress.generated.ts', import.meta.url);
const only = process.argv[2];
const UA = { 'User-Agent': 'RacingHub/0.1 (personal noncommercial project)' };

/** "PREINING Thomas" → "Thomas Preining" (the API writes the family name in capitals first). */
function driverName(name) {
  const words = name.trim().split(/\s+/);
  const family = [];
  while (words.length > 1 && words[0] === words[0].toUpperCase() && /\p{Lu}/u.test(words[0]))
    family.push(words.shift());
  const cap = (w) => w.charAt(0) + w.slice(1).toLowerCase();
  // Particles stay lower case before the rest of the family name: "van der Linde".
  const surname = family.map((w, i) =>
    i < family.length - 1 && /^(VAN|DER|DEN|DE|DA|DI|VON|LE|LA)$/.test(w)
      ? w.toLowerCase()
      : w.split('-').map(cap).join('-'),
  );
  return [...words, ...surname].join(' ');
}

async function season(year) {
  const url = `https://api.dtm.com/data?query=wigeStandings&raceSeries=DTM&startDate=${year}-01-01&endDate=${year}-12-31&lang=en`;
  const res = await fetch(url, { headers: UA, signal: AbortSignal.timeout(30000) });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const { wigeStandingses: list } = await res.json();
  if (!list?.length) return null;
  const data = JSON.parse(list[0].jsonText);
  const races = data.pointsessions.map((s) => s.name);
  const out = { rounds: races };
  for (const kind of ['drivers', 'teams', 'manufacturers']) {
    const rows = data[kind] ?? [];
    let ok = rows.length > 0;
    const series = rows.map((row) => {
      let sum = 0;
      const points = races.map((race) => {
        const r = row.races.find((x) => x.name === race);
        const value = r && r.points !== '' && r.points != null ? Number(r.points) : null;
        if (value === null) return sum ? sum : null;
        sum += value;
        return sum;
      });
      if (sum !== Number(row.totalpoints)) {
        console.log(`${year} ${kind}: ${row.name} sums to ${sum}, published ${row.totalpoints}`);
        ok = false;
      }
      return [kind === 'drivers' ? driverName(row.name) : row.name, points];
    });
    if (ok) out[kind] = series;
  }
  console.log(
    `${year}: ${races.length} races, ${['drivers', 'teams', 'manufacturers'].filter((k) => out[k]).join(', ') || 'nothing verified'}`,
  );
  return ['drivers', 'teams', 'manufacturers'].some((k) => out[k]) ? out : null;
}

const MARK = '// DATA';
let all = {};
try {
  const text = await readFile(OUT, 'utf8');
  all = JSON.parse(text.slice(text.indexOf('= {', text.indexOf(MARK)) + 2, text.lastIndexOf(';')));
} catch {
  /* first run */
}
for (let y = 2000; y <= new Date().getFullYear(); y++) {
  if (only && only !== String(y)) continue;
  const result = await season(String(y));
  if (result) all[y] = result;
  else delete all[y];
}
const sorted = Object.fromEntries(Object.entries(all).sort(([a], [b]) => b.localeCompare(a)));
await writeFile(
  OUT,
  `// Generated by scripts/fetch-dtm-points.mjs from api.dtm.com (official points of every race, summed and checked).\n` +
    `import type { DtmPublishedPoints } from './standingProgress';\n\n` +
    `${MARK}\nexport const dtmPublishedPoints: Record<string, DtmPublishedPoints> = ${JSON.stringify(sorted, null, 1)};\n`,
);
