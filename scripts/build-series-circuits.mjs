// Circuit outlines for IMSA and DTM. Run: node scripts/build-series-circuits.mjs
// Geometry: © OpenStreetMap contributors, ODbL, through tobi/track-atlas (pinned revision);
// length, corners and direction are the atlas's own figures for that layout. Only the current
// layout is drawn, so pages show it as the present-day configuration.
import { writeFile } from 'node:fs/promises';

const REVISION = '8c12ac414ea74ffe4a3ef74b294a2eafab7ee60d';
const BASE = `https://raw.githubusercontent.com/tobi/track-atlas/${REVISION}`;
// Circuits IMSA and DTM race on that the atlas has (Detroit, Lausitzring, Norisring, Oschersleben,
// Nürburgring, Sachsenring and Hockenheim are not in it). Preferred layout id first.
const TRACKS = {
  daytona: ['gp'],
  sebring: ['imsa', 'gp'],
  'long-beach': ['gp'],
  'laguna-seca': ['gp'],
  'watkins-glen': ['gp'],
  mosport: ['gp'],
  'road-america': ['gp'],
  'virginia-international-raceway': ['gp'],
  indianapolis: ['gp'],
  'road-atlanta': ['gp'],
  'circuit-of-the-americas': ['gp'],
  'lime-rock': ['gp'],
  'red-bull-ring': ['gp'],
  zandvoort: ['gp'],
};

const index = await (await fetch(`${BASE}/tracks/index.json`)).json();
const out = {};
for (const [slug, prefer] of Object.entries(TRACKS)) {
  const track = index.tracks.find((t) => t.slug === slug);
  const meta = prefer.map((id) => track?.layouts.find((l) => l.id === id)).find(Boolean);
  if (!track || !meta) throw new Error(`No layout for ${slug}`);
  const path = `tracks/${slug}/raw/layers/${meta.id}.geojson`;
  const response = await fetch(`${BASE}/${path}`);
  if (!response.ok) throw new Error(`${response.status}: ${path}`);
  const json = await response.json();
  const outline = json.features.find((feature) => feature.properties.role === 'outline');
  if (outline?.geometry.type !== 'LineString') throw new Error(`No outline: ${path}`);
  const coordinates = outline.geometry.coordinates;
  if (
    coordinates.length < 20 ||
    coordinates.some((p) => p.length !== 2 || p.some((n) => !Number.isFinite(n)))
  )
    throw new Error(`Invalid coordinates: ${path}`);
  const latitude = coordinates.reduce((sum, p) => sum + p[1], 0) / coordinates.length;
  const longitudeScale = Math.cos((latitude * Math.PI) / 180);
  const points = coordinates.map(([lon, lat]) => [lon * longitudeScale, -lat]);
  const minX = Math.min(...points.map((p) => p[0]));
  const minY = Math.min(...points.map((p) => p[1]));
  const width = Math.max(...points.map((p) => p[0])) - minX;
  const height = Math.max(...points.map((p) => p[1])) - minY;
  const scale = 460 / Math.max(width, height);
  const d =
    points
      .map(
        ([x, y], i) =>
          `${i ? 'L' : 'M'}${(20 + (x - minX) * scale).toFixed(1)} ${(20 + (y - minY) * scale).toFixed(1)}`,
      )
      .join('') + 'Z';
  out[slug] = {
    name: track.name,
    aka: track.aka ?? [],
    layoutName: meta.name,
    layout: {
      eras: [[0, 9999]],
      lengthKm: Math.round(meta.length_m) / 1000,
      turns: meta.corners,
      direction: meta.direction === 'anticlockwise' ? 'anticlockwise' : 'clockwise',
      d,
      source: {
        name: '© OpenStreetMap contributors · track-atlas',
        url: `https://github.com/tobi/track-atlas/blob/${REVISION}/${path}`,
        license: 'ODbL',
        licenseUrl: 'https://opendatacommons.org/licenses/odbl/1-0/',
        changes: 'контур приведён к масштабу; длина и число поворотов — данные track-atlas',
      },
    },
  };
}

await writeFile(
  new URL('../src/data/circuits/atlas.generated.ts', import.meta.url),
  `// Generated by scripts/build-series-circuits.mjs; do not edit by hand.\n// Geometry: © OpenStreetMap contributors, ODbL 1.0, through tobi/track-atlas.\nimport type { CircuitLayout } from './types';\n\nexport const ATLAS: Record<string, { name: string; aka: string[]; layoutName: string; layout: CircuitLayout }> = ${JSON.stringify(out)};\n`,
  'utf8',
);
console.log(`Bundled ${Object.keys(out).length} outlines (${REVISION}).`);
