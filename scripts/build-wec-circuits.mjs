// Bundles two WEC-only outlines. Run: node scripts/build-wec-circuits.mjs
// Geometry: © OpenStreetMap contributors, ODbL, through tobi/track-atlas.
// Only the outline is used; upstream corner metadata is not copied.
import { writeFile } from 'node:fs/promises';

const REVISION = '8c12ac414ea74ffe4a3ef74b294a2eafab7ee60d';
const BASE = `https://raw.githubusercontent.com/tobi/track-atlas/${REVISION}`;
const tracks = [
  {
    id: 'sarthe',
    slug: 'circuit-de-la-sarthe',
    layout: '24h',
    eras: [[2018, 2026]],
    lengthKm: 13.626,
    turns: 38,
  },
  { id: 'sebring', slug: 'sebring', layout: 'wec', eras: [[2012, 2026]], lengthKm: 6.019, turns: 17 },
];

const layouts = {};
for (const { id, slug, layout, ...stats } of tracks) {
  const path = `tracks/${slug}/raw/layers/${layout}.geojson`;
  const response = await fetch(`${BASE}/${path}`);
  if (!response.ok) throw new Error(`${response.status}: ${path}`);
  const json = await response.json();
  const outline = json.features.find((feature) => feature.properties.role === 'outline');
  if (outline?.geometry.type !== 'LineString') throw new Error(`No outline: ${path}`);
  const coordinates = outline.geometry.coordinates;
  if (
    coordinates.length < 20 ||
    coordinates.some((p) => p.length !== 2 || p.some((n) => !Number.isFinite(n)))
  ) {
    throw new Error(`Invalid coordinates: ${path}`);
  }
  const latitude = coordinates.reduce((sum, p) => sum + p[1], 0) / coordinates.length;
  const longitudeScale = Math.cos((latitude * Math.PI) / 180);
  const points = coordinates.map(([lon, lat]) => [lon * longitudeScale, -lat]);
  const minX = Math.min(...points.map((p) => p[0]));
  const minY = Math.min(...points.map((p) => p[1]));
  const width = Math.max(...points.map((p) => p[0])) - minX;
  const height = Math.max(...points.map((p) => p[1])) - minY;
  const scale = 460 / Math.max(width, height);
  const d =
    points
      .map(
        ([x, y], i) =>
          `${i ? 'L' : 'M'}${(20 + (x - minX) * scale).toFixed(2)} ${(20 + (y - minY) * scale).toFixed(2)}`,
      )
      .join('') + 'Z';
  layouts[id] = {
    ...stats,
    direction: 'clockwise',
    d,
    source: {
      name: '© OpenStreetMap contributors · track-atlas',
      url: `https://github.com/tobi/track-atlas/blob/${REVISION}/${path}`,
      license: 'ODbL',
      licenseUrl: 'https://opendatacommons.org/licenses/odbl/1-0/',
      changes: 'контур приведён к масштабу',
    },
  };
}

await writeFile(
  new URL('../src/series/wec/data/circuit-shapes.generated.ts', import.meta.url),
  `// Generated by scripts/build-wec-circuits.mjs; do not edit by hand.\n// Geometry: © OpenStreetMap contributors, ODbL 1.0.\n// https://opendatacommons.org/licenses/odbl/1-0/\n// Length and turns: FIA WEC event data, see circuits.ts.\nimport type { CircuitLayout } from '../../../data/circuits';\n\nexport const WEC_LAYOUTS: Record<string, CircuitLayout> = ${JSON.stringify(layouts, null, 2)};\n`,
  'utf8',
);
console.log(`Bundled ${Object.keys(layouts).length} WEC outlines (${REVISION}).`);
