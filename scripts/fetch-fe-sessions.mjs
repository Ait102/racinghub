// Free practice classifications of Formula E from the official results (results.formulae.fia.com):
// the "Classification" CSV of every practice session, as the timing writes it. Race and
// qualifying already come from Wikipedia; practice has no other source.
//
//   node scripts/fetch-fe-sessions.mjs            the two newest seasons with results
//   node scripts/fetch-fe-sessions.mjs 2024-25    one season
import { writeFile } from 'node:fs/promises';

const BASE = 'https://d112sbqg9gqc2x.cloudfront.net/';
const ROOT = 'formula-e/files/results';
const only = process.argv[2];
const url = (id) => BASE + id.split('/').map(encodeURIComponent).join('/');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function get(id, json = true) {
  await sleep(120);
  const res = await fetch(json ? `${url(id)}/index.json` : url(id), { signal: AbortSignal.timeout(30000) });
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`);
  return json ? res.json() : res.text();
}

const cap = (w) => (/[a-z]/.test(w) ? w : w.charAt(0) + w.slice(1).toLowerCase());
const name = (first, second) =>
  `${first} ${second
    .split(/(\s+|-)/)
    .map(cap)
    .join('')
    .replace(/\b(De|Da|Di|Van|Der)\b(?= )/g, (p) => p.toLowerCase())}`.trim();

function rows(csv) {
  const [head, ...lines] = csv.replace(/^﻿/, '').trim().split(/\r?\n/);
  const cols = head.split(';').map((c) => c.trim());
  return lines.filter(Boolean).map((line) => {
    const v = line.split(';');
    const at = (c) => (cols.indexOf(c) >= 0 ? (v[cols.indexOf(c)] ?? '').trim() : '');
    // Row: [position, number, driver, team, best lap, gap, laps]
    // Some teams come in capitals ("MAHINDRA RACING"): written as words, acronyms kept.
    const team = /[a-z]/.test(at('TEAM'))
      ? at('TEAM')
      : at('TEAM')
          .split(' ')
          .map((w) => (/^(DS|ABT|NIO|ERT|TAG|NEOM|TCS|MSG|E)$/.test(w) ? w : cap(w)))
          .join(' ');
    return [
      at('POS'),
      at('NUMBER'),
      name(at('DRIVER_FIRSTNAME'), at('DRIVER_SECONDNAME')),
      team,
      at('TIME'),
      at('GAP_FIRST'),
      at('LAPS'),
    ];
  });
}

const seasons = (await get(ROOT)).items.filter((s) => /\d{4}-\d{2}$/.test(s.title));
let done = 0;
for (const entry of seasons) {
  const id = /(\d{4}-\d{2})$/.exec(entry.title)[1];
  if (only ? id !== only : done >= 2) continue;
  const out = {};
  for (const round of (await get(entry.id))?.items ?? []) {
    const m = /^R(\d+)\s/.exec(round.title);
    if (!m || Number(m[1]) === 0) continue;
    const event = await get(round.id);
    const group = event?.items.find(
      (g) => /Formula E.*Championship/i.test(g.title) && !/rookie/i.test(g.title),
    );
    const docs = group ? ((await get(group.id))?.items ?? []) : [];
    const sessions = [];
    for (const doc of docs.filter((d) => /^Free Practice \d$/i.test(d.title)).reverse()) {
      const files = (await get(doc.id))?.items ?? [];
      const csv = files.find((f) => f.extention === 'csv' && /Classification_/i.test(f.fileName));
      if (!csv) continue;
      sessions.push({
        label: `Свободная практика ${doc.title.slice(-1)}`,
        rows: rows(await get(csv.id, false)),
      });
    }
    if (sessions.length) out[Number(m[1])] = sessions;
  }
  if (!Object.keys(out).length) continue;
  done++;
  await writeFile(
    new URL(`../src/series/fe/data/sessions/${id}.ts`, import.meta.url),
    `// Generated by scripts/fetch-fe-sessions.mjs: official free practice classifications (results.formulae.fia.com).\n` +
      `// Row: [position, number, driver, team, best lap, gap, laps].\n` +
      `import type { FeSessionsByRound } from '../sessions';\n\n` +
      `export const SESSIONS: FeSessionsByRound = ${JSON.stringify(out)};\n`,
  );
  console.log(`${id}: ${Object.keys(out).length} rounds with practice`);
}
